export const RENAME_RULES = new Set(['camelCase', 'kebab-case', 'snake_case', 'PascalCase']);

export function isPlainObject(value) {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

/** Splits PascalCase, camelCase, snake_case, or kebab-case into lowercase words. */
export function splitWords(input) {
  const normalized = String(input)
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2')
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2')
    .replace(/[-_.\s/]+/g, ' ')
    .trim();
  return normalized.length === 0 ? [] : normalized.split(' ').map((w) => w.toLowerCase());
}

export function toSnakeCase(input) {
  return splitWords(input).join('_');
}

export function toScreamingSnake(input) {
  return splitWords(input)
    .map((w) => w.toUpperCase())
    .join('_');
}

export function toKebabCase(input) {
  return splitWords(input).join('-');
}

export function toPascalCase(input) {
  return splitWords(input)
    .map((w) => (w.length > 0 ? w[0].toUpperCase() + w.slice(1) : ''))
    .join('');
}

export function toCamelCase(input) {
  const words = splitWords(input);
  if (words.length === 0) return '';
  return (
    words[0] +
    words
      .slice(1)
      .map((w) => (w.length > 0 ? w[0].toUpperCase() + w.slice(1) : ''))
      .join('')
  );
}

export function applyRename(name, renameAll) {
  if (!renameAll) return name;
  switch (renameAll) {
    case 'camelCase':
      return toCamelCase(name);
    case 'kebab-case':
      return toKebabCase(name);
    case 'snake_case':
      return toSnakeCase(name);
    case 'PascalCase':
      return toPascalCase(name);
    default:
      return name;
  }
}

export function isOptionalType(typeExpr) {
  return isPlainObject(typeExpr) && Object.hasOwn(typeExpr, 'optional');
}

export function unwrapFieldType(field) {
  let inner = field.type;
  let optional = Boolean(field.optional);
  while (isOptionalType(inner)) {
    optional = true;
    inner = inner.optional;
  }
  return { inner, optional };
}

export function resolveWireName(item, renameAll) {
  if (typeof item.wire === 'string' && item.wire.length > 0) {
    return item.wire;
  }
  return applyRename(item.name, renameAll);
}

export function inferConstType(value, explicitType) {
  if (explicitType) return explicitType;
  if (typeof value === 'string') return 'string';
  if (typeof value === 'boolean') return 'bool';
  if (typeof value === 'number') {
    if (Number.isInteger(value)) {
      return value < 0 ? 'i32' : 'u32';
    }
    return 'f64';
  }
  throw new Error(`Unsupported constant value type: ${typeof value}`);
}

export function escapeDoubleQuoted(str) {
  return JSON.stringify(str);
}

export function escapeSingleQuoted(str) {
  return `'${String(str).replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n').replace(/\r/g, '\\r').replace(/\t/g, '\\t')}'`;
}

export function selectSectionEntries(sectionObj, include, sectionKey) {
  const entries = Object.entries(sectionObj ?? {});
  if (!include) return entries;
  const rule = include[sectionKey];
  if (rule === true) return entries;
  if (!rule) return [];
  const wanted = new Set(rule);
  return entries.filter(([key]) => wanted.has(key));
}

export function selectSpecSections(spec, include) {
  return {
    constants: selectSectionEntries(spec.constants, include, 'constants'),
    enums: selectSectionEntries(spec.enums, include, 'enums'),
    structs: selectSectionEntries(spec.structs, include, 'structs'),
    taggedUnions: selectSectionEntries(spec.taggedUnions, include, 'taggedUnions'),
    rpcs: selectSectionEntries(spec.rpcs, include, 'rpcs'),
    events: selectSectionEntries(spec.events, include, 'events'),
  };
}

export function pushBlockDoc(lines, doc, indent = '') {
  if (!doc) return;
  const parts = String(doc).split('\n');
  if (parts.length === 1) {
    lines.push(`${indent}/** ${parts[0]} */`);
    return;
  }
  lines.push(`${indent}/**`);
  for (const line of parts) {
    lines.push(line.length > 0 ? `${indent} * ${line}` : `${indent} *`);
  }
  lines.push(`${indent} */`);
}

export function typeExprSome(typeExpr, predicate) {
  if (predicate(typeExpr)) return true;
  if (!isPlainObject(typeExpr)) return false;
  if (Object.hasOwn(typeExpr, 'list')) return typeExprSome(typeExpr.list, predicate);
  if (Object.hasOwn(typeExpr, 'optional')) return typeExprSome(typeExpr.optional, predicate);
  if (Object.hasOwn(typeExpr, 'map')) {
    return typeExprSome(typeExpr.map[0], predicate) || typeExprSome(typeExpr.map[1], predicate);
  }
  return false;
}

export function sectionsUseType(selected, predicate) {
  for (const [, def] of selected.structs) {
    if (def.fields.some((f) => typeExprSome(f.type, predicate))) return true;
  }
  for (const [, def] of selected.taggedUnions) {
    for (const v of def.variants) {
      if (v.payload && typeExprSome(v.payload, predicate)) return true;
      if (v.fields?.some((f) => typeExprSome(f.type, predicate))) return true;
    }
  }
  return false;
}

export function buildHeaderLines(header) {
  const lines = [`// ${GENERATED_BANNER}`];
  if (header) {
    for (const line of String(header).split('\n')) {
      lines.push(line.startsWith('//') ? line : `// ${line}`);
    }
  }
  return lines;
}

export function mapStringConstEntries(entries, field) {
  return entries.map(([k, item]) => [k, { value: item[field], type: 'string', doc: item.doc }]);
}
