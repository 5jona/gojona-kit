#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { diffContractSpecs } from './diff.mjs';
import { emitKotlin } from './emitKotlin.mjs';
import { emitRust } from './emitRust.mjs';
import { emitSchema } from './emitSchema.mjs';
import { emitTs } from './emitTs.mjs';
import { loadContractSpec } from './spec.mjs';
import { collectFixtureFiles, validateFixtureFile } from './validator.mjs';

const USAGE = [
  'Usage: pochita-contracts-gen <command> [args...]',
  '',
  'Commands:',
  '  generate <spec.json...>                        Emit all configured targets deterministically',
  '  check <spec.json...>                           Verify disk outputs match generated bytes (exit 1 on drift)',
  '  diff [--json] <base-spec.json> <head-spec.json> Detect breaking wire changes between two specs',
  '  validate-fixtures <schema.json> <paths...>     Validate JSON fixtures against $defs/<TypeName>',
].join('\n');

function emitTarget(spec, output) {
  switch (output.target) {
    case 'rust':
      return emitRust(spec, output);
    case 'kotlin':
      return emitKotlin(spec, output);
    case 'ts':
      return emitTs(spec, output);
    case 'jsonSchema':
      return emitSchema(spec, output);
    default:
      throw new Error(`Unsupported target "${output.target}"`);
  }
}

/** Compiles one spec file into `{ target, absPath, content }[]` without writing to disk. */
export function compileSpecFile(specPath) {
  const { spec, baseDir } = loadContractSpec(specPath);
  return spec.outputs.map((output) => ({
    target: output.target,
    absPath: path.resolve(baseDir, output.path),
    content: emitTarget(spec, output),
  }));
}

function runGenerate(specPaths, io) {
  if (specPaths.length === 0) {
    io.err('Error: generate requires at least one spec file.');
    return 1;
  }
  let written = 0;
  let unchanged = 0;
  for (const specPath of specPaths) {
    for (const artifact of compileSpecFile(specPath)) {
      fs.mkdirSync(path.dirname(artifact.absPath), { recursive: true });
      const prev = fs.existsSync(artifact.absPath)
        ? fs.readFileSync(artifact.absPath, 'utf8')
        : null;
      if (prev === artifact.content) {
        unchanged++;
      } else {
        fs.writeFileSync(artifact.absPath, artifact.content, 'utf8');
        written++;
      }
    }
  }
  io.out(`Generated contracts: ${written} written, ${unchanged} unchanged.`);
  return 0;
}

function runCheck(specPaths, io) {
  if (specPaths.length === 0) {
    io.err('Error: check requires at least one spec file.');
    return 1;
  }
  const drifted = [];
  let total = 0;
  for (const specPath of specPaths) {
    for (const artifact of compileSpecFile(specPath)) {
      total++;
      const exists = fs.existsSync(artifact.absPath);
      const current = exists ? fs.readFileSync(artifact.absPath, 'utf8') : null;
      if (!exists || current !== artifact.content) {
        drifted.push({
          absPath: artifact.absPath,
          reason: exists ? 'content drift' : 'missing file',
        });
      }
    }
  }
  if (drifted.length > 0) {
    io.err(`Contract drift detected in ${drifted.length}/${total} file(s):`);
    for (const item of drifted) {
      io.err(`  - ${item.absPath} (${item.reason})`);
    }
    return 1;
  }
  io.out(`Contract check passed: ${total} file(s) up to date.`);
  return 0;
}

function runValidateFixtures(args, io) {
  if (args.length < 2) {
    io.err('Error: validate-fixtures requires <schema.json> and at least one fixture path.');
    return 1;
  }
  const [schemaPath, ...fixtureTargets] = args;
  const rootSchema = JSON.parse(fs.readFileSync(path.resolve(schemaPath), 'utf8'));
  const fixtureFiles = collectFixtureFiles(fixtureTargets);
  if (fixtureFiles.length === 0) {
    io.err('Error: no JSON fixture files found.');
    return 1;
  }

  let passed = 0;
  const failures = [];
  for (const file of fixtureFiles) {
    const result = validateFixtureFile(rootSchema, file);
    if (result.ok) {
      passed++;
    } else {
      failures.push(result);
    }
  }

  if (failures.length > 0) {
    io.err(`Fixture validation failed (${failures.length}/${fixtureFiles.length} failed):`);
    for (const f of failures) {
      io.err(`  - ${f.file} [${f.defName ?? 'unknown'}]:`);
      for (const errMsg of f.errors) {
        io.err(`      ${errMsg}`);
      }
    }
    return 1;
  }

  io.out(`Fixture validation passed: ${passed}/${fixtureFiles.length} fixture(s).`);
  return 0;
}

function runDiff(args, io) {
  let jsonOutput = false;
  const positional = [];
  for (const arg of args) {
    if (arg === '--json') {
      jsonOutput = true;
    } else if (arg.startsWith('-')) {
      io.err(`Error: unknown option "${arg}" for diff.`);
      return 1;
    } else {
      positional.push(arg);
    }
  }
  if (positional.length !== 2) {
    io.err('Error: diff requires <base-spec.json> <head-spec.json>.');
    return 1;
  }
  const { spec: baseSpec } = loadContractSpec(positional[0]);
  const { spec: headSpec } = loadContractSpec(positional[1]);
  const result = diffContractSpecs(baseSpec, headSpec);

  if (jsonOutput) {
    io.out(JSON.stringify(result, null, 2));
    return result.ok ? 0 : 1;
  }
  if (!result.ok) {
    io.err(
      `Breaking contract changes detected (${result.breaking.length} breaking, ${result.compatible.length} compatible):`,
    );
    for (const item of result.breaking) {
      io.err(`  [BREAKING] ${item.code} ${item.path}: ${item.message}`);
    }
    return 1;
  }
  io.out(`Contract diff passed: 0 breaking, ${result.compatible.length} compatible change(s).`);
  for (const item of result.compatible) {
    io.out(`  [COMPATIBLE] ${item.code} ${item.path}: ${item.message}`);
  }
  return 0;
}

/** Programmatic CLI entrypoint returning a numeric exit code. */
export function runCli(
  argv,
  io = {
    out: (msg) => console.log(msg),
    err: (msg) => console.error(msg),
  },
) {
  const [cmd, ...rest] = argv;
  if (!cmd || cmd === '--help' || cmd === '-h') {
    io.out(USAGE);
    return cmd ? 0 : 1;
  }
  try {
    if (cmd === 'generate') return runGenerate(rest, io);
    if (cmd === 'check') return runCheck(rest, io);
    if (cmd === 'diff') return runDiff(rest, io);
    if (cmd === 'validate-fixtures') return runValidateFixtures(rest, io);
    io.err(`Unknown command "${cmd}".\n\n${USAGE}`);
    return 1;
  } catch (err) {
    io.err(`Error: ${err instanceof Error ? err.message : String(err)}`);
    return 1;
  }
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (isMain) {
  process.exitCode = runCli(process.argv.slice(2));
}
